// ============================================
// partBlocks — the "mis-splits bias safe" claim
// ============================================
//
// The claim under test: when partBlocks mis-splits, it UNDER-counts ownership,
// which yields `fork`/`add` (additive) rather than `update` (destructive).
//
// It holds for every shape above. It does NOT hold universally — see the bare
// `-` case below.

Deno.test("partBlocks: a bare `-` sequence entry still opens a new part", () => {
  // REGRESSION. `-` alone on a line, with the entry's keys on the following
  // lines, is valid YAML and a common hand-editing style. The splitter used
  // to require `-` followed by whitespace (/^\s*-\s/), so a bare `-` did not
  // open a block and part B's lines were appended to part A's.
  //
  // That merge was an OVER-count, and in the destructive direction. blockValue
  // takes the first match of each key, so the merged block answered with part
  // A's `type:` and part B's `submitted_by:` — an imported chart followed by
  // the caller's own tab read as "the caller submitted a LEAD SHEET here",
  // which is an in-place edit right over somebody else's chart. The exact
  // escalation the type scoping closes, reached through whitespace instead.
  //
  // Nothing in the pipeline emits this style (works_writer uses PyYAML's
  // `- key: value`), so it is not submitter-reachable — but `works/` is the
  // hand-editable store by design, so that is not a defence.
  const yaml = `id: angeline-the-baker
title: Angeline the Baker
parts:
- type: lead-sheet
  format: chordpro
  file: lead-sheet.pro
  default: true
  provenance:
    source: tunearch
    imported_at: '2026-07-26'
-
  type: tablature
  instrument: banjo
  format: otf
  file: banjo.otf.json
  provenance:
    source: user-submission
    submitted_by: ${STRANGER}
`
  assertEquals(partBlocks(yaml).length, 2)
  // The tab submitter owns the tab and NOT the chart.
  assertEquals(submittersOf(yaml, "lead-sheet"), [])
  assertEquals(submittersOf(yaml, "tablature"), [STRANGER])
  assertEquals(tabPartOwners(yaml, "banjo.otf.json"), [STRANGER])
})

Deno.test("partBlocks: a `---` document marker does not start a block", () => {
  const yaml = `---
id: x
parts:
- type: lead-sheet
  file: lead-sheet.pro
  provenance:
    submitted_by: ${PRIMARY_CHART_OWNER}
`
  assertEquals(partBlocks(yaml).length, 1)
  assertEquals(submittersOf(yaml, "lead-sheet"), [PRIMARY_CHART_OWNER])
})

