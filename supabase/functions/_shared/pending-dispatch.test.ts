/** Minimal stand-in for the bits of SupabaseClient this function touches. */
// deno-lint-ignore no-explicit-any
function fakeAdmin(result: { count?: number | null; error?: { message: string } }): any {
  const chain = {
    select: () => chain,
    eq: () => chain,
    gte: () => Promise.resolve(result),
  }
  return { from: () => chain }
}

Deno.test("submissionsInLastHour: returns the counted rows", async () => {
  assertEquals(await submissionsInLastHour(fakeAdmin({ count: 7 }), "u"), 7)
  assertEquals(await submissionsInLastHour(fakeAdmin({ count: 0 }), "u"), 0)
  assertEquals(await submissionsInLastHour(fakeAdmin({ count: null }), "u"), 0)
})

Deno.test("submissionsInLastHour: fails OPEN when the count errors", async () => {
  // Deliberate: a hiccuping SELECT must not lock everyone out of contributing.
  // Size caps and RLS are still in force.
  const n = await submissionsInLastHour(fakeAdmin({ error: { message: "boom" } }), "u")
  assertEquals(n, 0)
  assertEquals(n < RATE_LIMIT_PER_HOUR, true)
})
