/** Base64 of a string's UTF-8 bytes — what the GitHub Contents API sends. */
function b64(text: string): string {
  let binary = ""
  for (const byte of new TextEncoder().encode(text)) {
    binary += String.fromCharCode(byte)
  }
  return btoa(binary)
}

/**
 * Run `fn` with `getFileContent` answering from `files` instead of the network.
 *
 * Keys are repo paths; a string value is the file's text, a number is an HTTP
 * status to return instead (404 = "no such work", 500 = a transient failure).
 * An unlisted path 404s.
 */
async function withGithub(
  files: Record<string, string | number>,
  fn: () => Promise<void>,
): Promise<void> {
  const real = globalThis.fetch
  globalThis.fetch = ((input: string | URL | Request) => {
    const url = String(input instanceof Request ? input.url : input)
    const path = decodeURIComponent(
      url.replace(/^.*\/contents\//, "").replace(/\?.*$/, ""),
    )
    const entry = files[path]
    if (entry === undefined) return Promise.resolve(new Response("", { status: 404 }))
    if (typeof entry === "number") {
      return Promise.resolve(new Response("boom", { status: entry }))
    }
    // Same shape the Contents API returns: base64 of the file's UTF-8 BYTES
    // in `.content`. (btoa() alone would reject any non-ASCII fixture, which
    // is exactly what the real API does not do.)
    return Promise.resolve(
      new Response(JSON.stringify({ content: b64(entry) }), { status: 200 }),
    )
  }) as typeof fetch
  try {
    await fn()
  } finally {
    globalThis.fetch = real
  }
}

